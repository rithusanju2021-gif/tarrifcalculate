import io
from reportlab.lib.pagesizes import letter, A4
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib import colors


def generate_itinerary_pdf(title, vehicle_name, total_km, total_cost, days_or_legs, is_multiday=False, notes=""):
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=36,
        leftMargin=36,
        topMargin=36,
        bottomMargin=36
    )

    story = []
    styles = getSampleStyleSheet()

    # Custom styles
    primary_color = colors.HexColor("#0f172a")
    accent_color = colors.HexColor("#0284c7")
    gold_color = colors.HexColor("#d97706")
    text_dark = colors.HexColor("#1e293b")
    border_color = colors.HexColor("#cbd5e1")
    bg_light = colors.HexColor("#f8fafc")

    header_title_style = ParagraphStyle(
        'HeaderTitle',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=20,
        leading=24,
        textColor=primary_color,
        alignment=1
    )

    sub_title_style = ParagraphStyle(
        'SubTitle',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=12,
        leading=16,
        textColor=accent_color,
        alignment=1
    )

    tagline_style = ParagraphStyle(
        'Tagline',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9,
        leading=12,
        textColor=colors.HexColor("#64748b"),
        alignment=1
    )

    section_heading = ParagraphStyle(
        'SectionHeading',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=13,
        leading=16,
        textColor=primary_color
    )

    body_bold = ParagraphStyle(
        'BodyBold',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=10,
        leading=13,
        textColor=text_dark
    )

    body_normal = ParagraphStyle(
        'BodyNormal',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9,
        leading=12,
        textColor=text_dark
    )

    # 1. Header
    story.append(Paragraph("RITHISH TOURS &amp; TRAVELS", header_title_style))
    story.append(Paragraph("South India Itinerary &amp; Official Vehicle Tariff Quotation", sub_title_style))
    story.append(Paragraph("Chennai, Tamil Nadu | Website: rithishtoursandtravels.in | Internal Quotation System", tagline_style))
    story.append(Spacer(1, 12))
    story.append(HRFlowable(width="100%", thickness=1.5, color=accent_color, spaceBefore=4, spaceAfter=14))

    # 2. Trip Overview Box
    trip_type = "Multi-Day South India Tour Package" if is_multiday else "One-Day Sightseeing Trip"
    overview_data = [
        [
            Paragraph("<b>Quotation For:</b> " + str(title), body_normal),
            Paragraph("<b>Vehicle Selected:</b> " + str(vehicle_name or "Standard Tourist Vehicle"), body_normal)
        ],
        [
            Paragraph("<b>Tour Type:</b> " + trip_type, body_normal),
            Paragraph(f"<b>Total Road Distance:</b> {total_km:.2f} km", body_normal)
        ],
        [
            Paragraph("<b>Generated By:</b> RTT Staff Planner", body_normal),
            Paragraph(f"<b>Estimated Quotation Total:</b> <font color='#d97706'><b>₹{total_cost:,.2f}</b></font>", body_bold)
        ]
    ]
    overview_table = Table(overview_data, colWidths=[270, 250])
    overview_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), bg_light),
        ('BOX', (0, 0), (-1, -1), 1, border_color),
        ('INNERGRID', (0, 0), (-1, -1), 0.5, border_color),
        ('TOPPADDING', (0, 0), (-1, -1), 6),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
        ('LEFTPADDING', (0, 0), (-1, -1), 8),
        ('RIGHTPADDING', (0, 0), (-1, -1), 8),
    ]))
    story.append(overview_table)
    story.append(Spacer(1, 16))

    if not is_multiday:
        # One-Day Detailed Legs Table
        story.append(Paragraph("Route Legs &amp; Road Distance Breakdown", section_heading))
        story.append(Spacer(1, 8))

        leg_rows = [
            [
                Paragraph("<b>#</b>", body_bold),
                Paragraph("<b>From Location</b>", body_bold),
                Paragraph("<b>To Location</b>", body_bold),
                Paragraph("<b>Distance</b>", body_bold),
                Paragraph("<b>Est. Time</b>", body_bold),
                Paragraph("<b>Data Source</b>", body_bold)
            ]
        ]

        legs = days_or_legs.get('legs', []) if isinstance(days_or_legs, dict) else days_or_legs
        for idx, leg in enumerate(legs, 1):
            src_tag = leg.get('source', 'LIVE')
            src_color = "#16a34a" if src_tag == 'LIVE' else ("#d97706" if src_tag == 'CACHED' else "#2563eb")
            leg_rows.append([
                Paragraph(str(idx), body_normal),
                Paragraph(leg.get('from', ''), body_normal),
                Paragraph(leg.get('to', ''), body_normal),
                Paragraph(f"{leg.get('distance_km', 0):.2f} km", body_normal),
                Paragraph(f"~{leg.get('duration_min', 0):.0f} min", body_normal),
                Paragraph(f"<font color='{src_color}'><b>{src_tag}</b></font>", body_normal)
            ])

        leg_table = Table(leg_rows, colWidths=[25, 145, 145, 75, 65, 65])
        leg_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#e2e8f0")),
            ('BOX', (0, 0), (-1, -1), 0.5, border_color),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, border_color),
            ('TOPPADDING', (0, 0), (-1, -1), 5),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
        ]))
        story.append(leg_table)
        story.append(Spacer(1, 14))

        # Tariff & Calculation Details
        story.append(Paragraph("Rental Tariff Calculation Breakdown", section_heading))
        story.append(Spacer(1, 8))
        tariff = days_or_legs.get('tariff', {}) if isinstance(days_or_legs, dict) else {}
        applied_method = days_or_legs.get('applied_method', 1)
        formula = days_or_legs.get('formula', '')

        tariff_rows = [
            [
                Paragraph("<b>Day Rent:</b> ₹" + str(tariff.get('day_rent', '0.00')), body_normal),
                Paragraph("<b>Fuel Rate:</b> ₹" + str(tariff.get('fuel_cost_per_km', '0.00')) + " / km", body_normal),
                Paragraph("<b>Included Limit:</b> " + str(tariff.get('included_km', '250')) + " km", body_normal),
            ],
            [
                Paragraph("<b>KM Rate (Method 2):</b> ₹" + str(tariff.get('km_rate', '0.00')) + " / km", body_normal),
                Paragraph("<b>Driver Bata:</b> ₹" + str(tariff.get('driver_bata', '0.00')), body_normal),
                Paragraph(f"<b>Applied:</b> Method {applied_method}", body_bold),
            ]
        ]
        t_table = Table(tariff_rows, colWidths=[170, 170, 180])
        t_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), bg_light),
            ('BOX', (0, 0), (-1, -1), 0.5, border_color),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, border_color),
            ('TOPPADDING', (0, 0), (-1, -1), 5),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
        ]))
        story.append(t_table)

        if formula:
            story.append(Spacer(1, 6))
            story.append(Paragraph(f"<b>Calculation Formula:</b> {formula}", body_normal))

    else:
        # Multi-Day Day-by-Day Table
        story.append(Paragraph("Day-Wise Itinerary &amp; Rental Breakdown", section_heading))
        story.append(Spacer(1, 8))

        day_rows = [
            [
                Paragraph("<b>Day</b>", body_bold),
                Paragraph("<b>Route / Sightseeing Destinations</b>", body_bold),
                Paragraph("<b>Halt</b>", body_bold),
                Paragraph("<b>Distance</b>", body_bold),
                Paragraph("<b>Method</b>", body_bold),
                Paragraph("<b>Day Total</b>", body_bold)
            ]
        ]

        days_list = days_or_legs if isinstance(days_or_legs, list) else days_or_legs.get('days', [])
        for day in days_list:
            stops_str = " &rarr; ".join([s.get('name', '') for s in day.get('stops', []) if s.get('name')])
            if not stops_str:
                stops_str = day.get('title', f"Day {day.get('day_number', '')}")
            m_tag = f"Method {day.get('applied_method', 1)}"
            day_cost = day.get('total_cost', 0)
            day_rows.append([
                Paragraph(f"Day {day.get('day_number', 1)}", body_bold),
                Paragraph(stops_str, body_normal),
                Paragraph(day.get('overnight_halt', '—'), body_normal),
                Paragraph(f"{day.get('actual_km', 0):.2f} km", body_normal),
                Paragraph(m_tag, body_normal),
                Paragraph(f"₹{day_cost:,.2f}", body_bold)
            ])

        day_table = Table(day_rows, colWidths=[40, 210, 80, 65, 60, 65])
        day_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#e2e8f0")),
            ('BOX', (0, 0), (-1, -1), 0.5, border_color),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, border_color),
            ('TOPPADDING', (0, 0), (-1, -1), 5),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
        ]))
        story.append(day_table)

    story.append(Spacer(1, 16))

    # 3. Final Summary Banner
    summary_data = [
        [
            Paragraph("<b>GRAND TOTAL QUOTATION:</b>", ParagraphStyle('SumH', parent=body_bold, fontSize=12, textColor=colors.white)),
            Paragraph(f"<b>₹{total_cost:,.2f}</b>", ParagraphStyle('SumV', parent=body_bold, fontSize=14, textColor=colors.HexColor("#fef08a"), alignment=2))
        ]
    ]
    summary_table = Table(summary_data, colWidths=[320, 200])
    summary_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), primary_color),
        ('TOPPADDING', (0, 0), (-1, -1), 8),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 8),
        ('LEFTPADDING', (0, 0), (-1, -1), 12),
        ('RIGHTPADDING', (0, 0), (-1, -1), 12),
    ]))
    story.append(summary_table)

    # Footer note
    story.append(Spacer(1, 14))
    story.append(Paragraph(
        "<b>Terms &amp; Notes:</b> Toll charges, parking fees, inter-state permit taxes (if applicable), and GST are extra at actuals unless explicitly negotiated. Night driving allowance applies after 10:00 PM. Rates calculated strictly by Rithish Tours &amp; Travels standard tariff rules.",
        ParagraphStyle('FooterNote', parent=styles['Normal'], fontSize=8, leading=10, textColor=colors.HexColor("#64748b"))
    ))

    doc.build(story)
    buffer.seek(0)
    return buffer.getvalue()
